import { Router } from 'express';
import { validate } from '../middleware/validate.js';
import { reviewService } from '../services/review.service.js';
import { createDailyReviewSchema, createWeeklyReviewSchema } from '@lifeos/shared';
import type { Request, Response, NextFunction } from 'express';

const router = Router();

// ── Daily Reviews ──

// GET /daily/:date - get daily review
router.get('/daily/:date', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const review = await reviewService.getDailyReview(req.params.date as string);
    if (!review) {
      res.status(404).json({ error: 'Daily review not found' });
      return;
    }
    res.json({ data: review });
  } catch (error) {
    next(error);
  }
});

// POST /daily - create/update daily review
router.post('/daily', validate(createDailyReviewSchema), async (req: Request, res: Response, next: NextFunction) => {
  try {
    const review = await reviewService.createDailyReview(req.body);
    res.status(201).json({ data: review });
  } catch (error) {
    next(error);
  }
});

// POST /daily/:date/generate - auto-generate daily review
router.post('/daily/:date/generate', async (req: Request, res: Response, next: NextFunction) => {
  try {
    const review = await reviewService.autoGenerateDaily(req.params.date as string);
    res.json({ data: review });
  } catch (error) {
    next(error);
  }
});

