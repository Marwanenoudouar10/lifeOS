import { prisma } from '../prisma.js';
import { formatDate } from '@lifeos/shared';
import type { CreateDailyReviewInput, CreateWeeklyReviewInput } from '@lifeos/shared';

// ── Daily Review CRUD ────────────────────────────────

async function getDailyReview(date: string) {
  const dateObj = new Date(date);
  dateObj.setUTCHours(0, 0, 0, 0);

  return prisma.dailyReview.findUnique({
    where: { date: dateObj },
  });
}

async function getAllDailyReviews(limit: number = 30, offset: number = 0) {
  return prisma.dailyReview.findMany({
    orderBy: { date: 'desc' },
    take: limit,
    skip: offset,
  });
}

async function createDailyReview(input: CreateDailyReviewInput) {
  const dateObj = new Date(input.date);
  dateObj.setUTCHours(0, 0, 0, 0);

  return prisma.dailyReview.create({
    data: {
      date: dateObj,
      mood: input.mood,
      energyLevel: input.energyLevel,
      wins: input.wins ?? [],
      challenges: input.challenges ?? [],
      notes: input.notes,
      gratitude: input.gratitude,
    },
  });
}

async function updateDailyReview(id: string, data: Partial<CreateDailyReviewInput>) {
  const { date, ...rest } = data;
  return prisma.dailyReview.update({
    where: { id },
    data: rest,
  });
}

async function removeDailyReview(id: string) {
  return prisma.dailyReview.delete({ where: { id } });
}

