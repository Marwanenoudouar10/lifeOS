// ── Auto-generate ────────────────────────────────────

async function autoGenerateDaily(date: string) {
  const dateObj = new Date(date);
  dateObj.setUTCHours(0, 0, 0, 0);

  const endOfDay = new Date(dateObj);
  endOfDay.setUTCHours(23, 59, 59, 999);

  // Count tasks completed on this date
  const tasksCompleted = await prisma.task.count({
    where: {
      completedAt: {
        gte: dateObj,
        lte: endOfDay,
      },
    },
  });

  // Count planned tasks for this date (from DailyPlan)
  const plan = await prisma.dailyPlan.findUnique({
    where: { date: dateObj },
    include: { items: true },
  });
  const tasksPlanned = plan?.items.length ?? 0;

  // Sum focus minutes from completed sessions on this date
  const focusSessions = await prisma.focusSession.findMany({
    where: {
      status: 'COMPLETED',
      startedAt: {
        gte: dateObj,
        lte: endOfDay,
      },
    },
    select: { totalSeconds: true },
  });

  const focusMinutes = Math.round(
    focusSessions.reduce((sum, s) => sum + s.totalSeconds, 0) / 60
  );

  // Upsert the daily review
  const review = await prisma.dailyReview.upsert({
    where: { date: dateObj },
    update: {
      tasksCompleted,
      tasksPlanned,
      focusMinutes,
    },
    create: {
      date: dateObj,
      tasksCompleted,
      tasksPlanned,
      focusMinutes,
    },
  });

  return review;
}

async function autoGenerateWeekly(weekStartDate: string) {
  const weekStart = new Date(weekStartDate);
  weekStart.setUTCHours(0, 0, 0, 0);

  const weekEnd = new Date(weekStart);
  weekEnd.setDate(weekEnd.getDate() + 6);
  weekEnd.setUTCHours(23, 59, 59, 999);

  // Tasks completed during the week
  const tasksCompleted = await prisma.task.count({
    where: {
      completedAt: {
        gte: weekStart,
        lte: weekEnd,
      },
    },
  });

  // Tasks created during the week
  const tasksCreated = await prisma.task.count({
    where: {
      createdAt: {
        gte: weekStart,
        lte: weekEnd,
      },
    },
  });

  // Sum focus minutes from completed sessions during the week
  const focusSessions = await prisma.focusSession.findMany({
    where: {
      status: 'COMPLETED',
      startedAt: {
        gte: weekStart,
        lte: weekEnd,
      },
    },
    select: { totalSeconds: true },
  });

  const focusMinutes = Math.round(
    focusSessions.reduce((sum, s) => sum + s.totalSeconds, 0) / 60
  );

  // Habit entries completed during the week
  const habitEntries = await prisma.habitEntry.findMany({
    where: {
      date: {
        gte: weekStart,
        lte: weekEnd,
      },
    },
    select: { habitId: true },
  });

  // Count unique habits that had at least one entry
  const habitsWithEntries = new Set(habitEntries.map((e) => e.habitId));

  // Count total active habits to determine missed
  const totalActiveHabits = await prisma.habit.count({
    where: { isActive: true },
  });

  // For a weekly view: habits completed = unique habits that checked in at least once
  // habits missed = active habits that had zero entries
  const habitsCompleted = habitsWithEntries.size;
  const habitsMissed = Math.max(0, totalActiveHabits - habitsCompleted);

  // Upsert the weekly review
  const review = await prisma.weeklyReview.upsert({
    where: { weekStart },
    update: {
      tasksCompleted,
      tasksCreated,
      focusMinutes,
      habitsCompleted,
      habitsMissed,
    },
    create: {
      weekStart,
      tasksCompleted,
      tasksCreated,
      focusMinutes,
      habitsCompleted,
      habitsMissed,
    },
  });

  return review;
}

